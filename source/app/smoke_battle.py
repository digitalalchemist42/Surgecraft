from playwright.sync_api import sync_playwright
import sys
def run(p, label, ctxargs, tap=False):
    out = {}; errs = []
    b = p.chromium.launch(); ctx = b.new_context(**ctxargs); pg = ctx.new_page()
    pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto("http://localhost:8765/test.html"); pg.wait_for_function("window.__muster && __muster.S.cur", timeout=20000); pg.wait_for_timeout(500)
    go = (lambda sel, n=0: pg.locator(sel).nth(n).tap()) if tap else (lambda sel, n=0: pg.locator(sel).nth(n).click())
    B = lambda expr: pg.evaluate("(()=>{const b=__muster.S.cur.battle; return %s})()" % expr)
    go('[data-a="tab"][data-v="battle"]'); pg.wait_for_timeout(300)
    out["setup_missions"] = pg.locator('[data-a="b-set"][data-v^="missionId:"]').count()
    go('[data-a="b-set"][data-v="missionId:frontlines"]'); go('[data-a="b-set"][data-v="color:blue"]'); pg.wait_for_timeout(200)
    pg.screenshot(path="bt_%s_setup.png" % label)
    go('[data-a="b-start"]'); pg.wait_for_timeout(400)
    out["started"] = B("[b.missionId,b.color,b.round,b.phase,Object.keys(b.units).length]")
    out["example_converted_to_saved"] = pg.evaluate("!__muster.S.cur.isExample")
    # deploy first three reserve units
    for k in range(3):
        go('.bunit.res [data-a="b-act"][data-v="deploy"]'); pg.wait_for_timeout(200)
    out["strip"] = pg.locator("#meters .meter").nth(1).inner_text().replace("\n"," | ")
    out["warn_after_deploys"] = pg.locator("#b-phase .check").all_inner_texts()
    # 4th deploy: expect over-supply warning (pool 6)
    go('.bunit.res [data-a="b-act"][data-v="deploy"]'); pg.wait_for_timeout(200)
    out["warn_4th"] = pg.locator("#b-phase .check").all_inner_texts()
    go('[data-a="b-undo"]'); pg.wait_for_timeout(200)
    out["after_undo_on_table"] = B("Object.values(b.units).filter(u=>u.st==='fld').length")
    pg.screenshot(path="bt_%s_move.png" % label, full_page=True)
    go('[data-a="b-end"]'); pg.wait_for_timeout(200); go('[data-a="b-pass"][data-v="opp"]'); pg.wait_for_timeout(300)
    out["phase2"] = B("[b.phase,b.fpm]")
    # damage + casualty on first fielded unit
    for k in range(3): go('.bunit.fld [data-a="b-d"][data-v="1"]'); pg.wait_for_timeout(120)
    out["casualty_prompt"] = pg.locator('.bunit.fld [data-a="b-cas"]').count()
    go('.bunit.fld [data-a="b-cas"]'); pg.wait_for_timeout(200)
    first = B("Object.values(b.units).filter(u=>u.st==='fld')[0]")
    out["first_unit_after_casualty"] = [first["m"], first["d"]]
    go('.bunit.fld [data-a="b-act"][data-v="charge"]'); pg.wait_for_timeout(200)
    out["ab_buttons"] = pg.locator('.bunit.fld [data-a="b-ab"]').count()
    if out["ab_buttons"]: go('.bunit.fld [data-a="b-ab"]'); pg.wait_for_timeout(200)
    out["abilities_shown"] = pg.locator(".bunit.fld .ab").count()
    out["kw_links_in_abilities"] = pg.locator(".bunit.fld .ab button.kw").count()
    if pg.locator('.bunit.fld [data-a="b-use"]').count(): go('.bunit.fld [data-a="b-use"]'); pg.wait_for_timeout(200)
    out["use_msgs"] = pg.locator("#b-phase .check").all_inner_texts()
    go('[data-a="b-card"]'); pg.wait_for_timeout(200)
    out["cards_title"] = pg.locator("#b-rail .panel h3").nth(2).inner_text()
    go('[data-a="b-mk"][data-v="1"]'); pg.wait_for_timeout(150); go('[data-a="b-mk"][data-v="2"]'); pg.wait_for_timeout(150); go('[data-a="b-mk"][data-v="2"]'); pg.wait_for_timeout(150)
    out["markers"] = B("[b.markers[1].own,b.markers[2].own]")
    pg.screenshot(path="bt_%s_assault.png" % label, full_page=True)
    go('[data-a="b-end"]'); pg.wait_for_timeout(150); go('[data-a="b-pass"][data-v="me"]'); pg.wait_for_timeout(300)
    go('[data-a="b-end"]'); pg.wait_for_timeout(200)
    out["combat_warning"] = pg.locator("#b-phase .check.warn").all_inner_texts()
    go('[data-a="b-pass"][data-v="go"]'); pg.wait_for_timeout(300)
    go('[data-a="b-inp"][data-v="enemyLost:1"]'); pg.wait_for_timeout(200)
    out["suggest_r1"] = pg.locator(".bs-col").all_inner_texts()
    pg.screenshot(path="bt_%s_scoring.png" % label, full_page=True)
    go('[data-a="b-confirm"]'); pg.wait_for_timeout(300)
    out["vp_r1"] = B("[b.vp.me, b.vp.opp, b.scored]")
    go('[data-a="b-next"]'); pg.wait_for_timeout(300)
    out["round2"] = B("[b.round,b.phase,b.fpm,b.rollOff]")
    # persistence: reload
    pg.wait_for_timeout(1200); pg.reload(); pg.wait_for_function("window.__muster && __muster.S.rosters.length>0", timeout=20000); pg.wait_for_timeout(600)
    out["saved_battle_round"] = pg.evaluate("(__muster.S.rosters.find(r=>r.battle)||{battle:{}}).battle.round")
    out["share_code_has_battle"] = pg.evaluate("JSON.stringify(__muster.C.exportable(__muster.S.rosters.find(r=>r.battle))).includes('battle')")
    out["pageerrors"] = errs
    b.close()
    print("=====", label)
    for k,v in out.items(): print(k, ":", v)
with sync_playwright() as p:
    run(p, "desk", {"viewport":{"width":1280,"height":900}})
    run(p, "phone", dict(p.devices["Pixel 7"]), tap=True)
