import json,re
G=json.load(open('glossary_all.json'))
USED=['ACCESS POINT','ANTI-EVADE','BUFF','BULKY','BURROWED','BURST FIRE','CONCENTRATED FIRE','CRITICAL HIT','DEBUFF','DISPLACEMENT','DODGE','GROUND LEVEL','HEAL','HIDDEN','HITS','IMPACT','IMPASSABLE TERRAIN','INDIRECT FIRE','INSTANT','LOCKED IN','LONG RANGE','MORPH','NON-LETHAL DAMAGE','ON CREEP','PIERCE','PINPOINT','PLACE','PRECISION','REPEATABLE','RESPAWN','SHIELDED','SIDEARM','SIEGE MODE','SPECIALIST','STATIONARY','STATUS','STAY IN PLAY','SUMMON','TOUGH']
def base(h):
    return re.sub(r'\s*(\(X\)|\[.*?\].*|Y” \(X\)|X \(Y\)|\(X\) Y|\(Unit Name\).*|\(LoS\))$','',h).strip()
out=[]; corrections=[]
for e in G:
    b=base(e['head'])
    if b not in USED: continue
    body=[dict(x) for x in e['body']]
    if b=='STATUS':
        for x in body:
            if 'by other means A Unit' in x['s']:
                a,c=x['s'].split('by other means ',1)
                x['s']=a+'by other means.'
                body.insert(body.index(x)+1,{'t':'p','s':c})
                corrections.append('STATUS: added the missing full stop after "removed by other means" and started the next sentence as its own paragraph, as laid out in the rulebook.')
                break
    out.append({'id':b.lower().replace(' ','-'),'term':b,'head':e['head'],'body':[[x['t'],x['s']] for x in body]})
assert len(out)==len(USED),(len(out),len(USED))
meta={'source':'Full Rules, Part 11: Keyword Glossary and Definitions (pp. 82–91)','scope':'Keywords that appear on unit, tactical, faction and creep cards','corrections':corrections}
js='/* SurgeCraft keyword reference — text verbatim from the Full Rules, Part 11. Generated by kw/make_js.py. */\n'
js+='(function (root) {\n  "use strict";\n  var DATA = '+json.dumps({'meta':meta,'list':out},ensure_ascii=False,indent=0).replace('</','<\\/')+';\n'
js+=r'''
  var STATUS_TITLE = { BURROWED: "Burrowed", SHIELDED: "Shielded", STATIONARY: "Stationary", HIDDEN: "Hidden" };
  var byTerm = {}, byId = {};
  DATA.list.forEach(function (k) { byTerm[k.term] = k; byId[k.id] = k; });
  var caps = DATA.list.filter(function (k) { return k.term !== "STATUS"; }).map(function (k) { return k.term; })
    .sort(function (a, b) { return b.length - a.length; })
    .map(function (t) { return t.replace(/[-]/g, "\\-"); });
  var titles = Object.keys(STATUS_TITLE).map(function (k) { return STATUS_TITLE[k]; });
  /* Upper-case keywords (optionally pluralised/past tense: ACCESS POINTS, DEBUFFS, PLACED), or a title-case status name followed by "Status". */
  var RE = new RegExp("(^|[^A-Za-z])(?:(" + caps.join("|") + ")(?:S|ED|D)?(?![A-Za-z])|(" + titles.join("|") + ")(?= Status))", "g");
  function find(text) {
    var out = [], m;
    RE.lastIndex = 0;
    while ((m = RE.exec(text))) {
      var start = m.index + m[1].length, word = m[0].slice(m[1].length), term = m[2] ? m[2] : m[3].toUpperCase();
      if (byTerm[term]) out.push({ start: start, end: start + word.length, id: byTerm[term].id });
      if (RE.lastIndex === m.index) RE.lastIndex++;
    }
    return out;
  }
  var Keywords = { meta: DATA.meta, list: DATA.list, byId: byId, byTerm: byTerm, find: find };
  if (typeof module !== "undefined" && module.exports) module.exports = Keywords; else root.Keywords = Keywords;
})(this);
'''
open('/home/claude/app/keywords.js','w').write(js)
json.dump({'meta':meta,'list':out},open('/home/claude/app/kw/keyword_reference.json','w'),indent=1,ensure_ascii=False)
print(len(out), corrections)
